import requests
from bs4 import BeautifulSoup
from urllib.parse import urljoin, urlparse
import pandas as pd
from google.colab import files
import time

# Configuration
START_URL = "http://www.foodsure.in/"
DOMAIN = urlparse(START_URL).netloc.replace("www.", "")
MAX_URLS = 500  # Safety limit to prevent infinite loops; increase if the site is larger

visited_urls = set()
urls_to_visit = [START_URL]
audit_data = []

headers = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
}

print(f"Starting SEO Crawl for: {START_URL}\n")

while urls_to_visit and len(visited_urls) < MAX_URLS:
    current_url = urls_to_visit.pop(0)

    # Normalize URL to avoid duplicate crawling of trailing slashes/fragments
    clean_url = current_url.split("#")[0].rstrip("/")
    if not clean_url:
        clean_url = START_URL.rstrip("/")

    if clean_url in visited_urls:
        continue

    visited_urls.add(clean_url)
    print(f"[{len(visited_urls)}] Crawling: {current_url}")

    try:
        start_time = time.time()
        response = requests.get(current_url, headers=headers, timeout=10)
        load_time = round(time.time() - start_time, 2)
        status_code = response.status_code

        # Process only HTML pages
        content_type = response.headers.get("Content-Type", "")
        if "text/html" not in content_type:
            continue

        soup = BeautifulSoup(response.text, "html.parser")

        # Extract Title
        title_tag = soup.find("title")
        title = title_tag.get_text(strip=True) if title_tag else "Missing"
        title_len = len(title) if title != "Missing" else 0

        # Extract Meta Description
        meta_desc_tag = soup.find("meta", attrs={"name": lambda x: x and x.lower() == "description"})
        meta_desc = meta_desc_tag["content"].strip() if meta_desc_tag and meta_desc_tag.get("content") else "Missing"
        meta_desc_len = len(meta_desc) if meta_desc != "Missing" else 0

        # Extract H1 Tags
        h1_tags = [h1.get_text(strip=True) for h1 in soup.find_all("h1")]
        h1_text = " | ".join(h1_tags) if h1_tags else "Missing"
        h1_count = len(h1_tags)

        # Extract H2 Count
        h2_count = len(soup.find_all("h2"))

        # Extract Canonical Tag
        canonical_tag = soup.find("link", rel="canonical")
        canonical = canonical_tag["href"].strip() if canonical_tag and canonical_tag.get("href") else "Missing"

        # Extract Meta Robots
        robots_tag = soup.find("meta", attrs={"name": lambda x: x and x.lower() == "robots"})
        robots = robots_tag["content"].strip() if robots_tag and robots_tag.get("content") else "Index, Follow (Default)"

        # Word Count
        text_content = soup.get_text(separator=" ", strip=True)
        word_count = len(text_content.split())

        # Image Alt Attribute Check
        images = soup.find_all("img")
        total_images = len(images)
        missing_alt = sum(1 for img in images if not img.get("alt") or not img.get("alt").strip())

        # Find Internal Links
        internal_links = 0
        for link in soup.find_all("a", href=True):
            href = link["href"].strip()
            full_url = urljoin(current_url, href)
            parsed_link = urlparse(full_url)

            # Filter for same domain and valid HTTP/HTTPS links
            if DOMAIN in parsed_link.netloc and parsed_link.scheme in ["http", "https"]:
                internal_links += 1
                normalized_next = full_url.split("#")[0].rstrip("/")

                # Exclude non-page files
                if not any(normalized_next.lower().endswith(ext) for ext in [".pdf", ".jpg", ".jpeg", ".png", ".gif", ".zip", ".doc", ".docx"]):
                    if normalized_next not in visited_urls and full_url not in urls_to_visit:
                        urls_to_visit.append(full_url)

        # Save Row Data
        audit_data.append({
            "URL": current_url,
            "Status Code": status_code,
            "Load Time (s)": load_time,
            "Title": title,
            "Title Length": title_len,
            "Meta Description": meta_desc,
            "Meta Desc Length": meta_desc_len,
            "H1 Tag": h1_text,
            "H1 Count": h1_count,
            "H2 Count": h2_count,
            "Canonical URL": canonical,
            "Meta Robots": robots,
            "Word Count": word_count,
            "Total Images": total_images,
            "Images Missing Alt": missing_alt,
            "Internal Links Found": internal_links
        })

    except Exception as e:
        audit_data.append({
            "URL": current_url,
            "Status Code": f"Error: {str(e)}",
            "Load Time (s)": 0,
            "Title": "Error",
            "Title Length": 0,
            "Meta Description": "Error",
            "Meta Desc Length": 0,
            "H1 Tag": "Error",
            "H1 Count": 0,
            "H2 Count": 0,
            "Canonical URL": "Error",
            "Meta Robots": "Error",
            "Word Count": 0,
            "Total Images": 0,
            "Images Missing Alt": 0,
            "Internal Links Found": 0
        })

# Create DataFrame and Export to Excel
df = pd.DataFrame(audit_data)
output_filename = "foodsure_seo_audit.xlsx"
df.to_excel(output_filename, index=False)

print(f"\nCrawl Complete! Total URLs audited: {len(df)}")
print(f"Downloading {output_filename} automatically...")

# Trigger Automatic Download in Browser
files.download(output_filename)